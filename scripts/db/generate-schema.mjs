// Generates scripts/db/schema.sql from a live Neon database (structure only, no data).
// Read-only: every query runs inside a READ ONLY transaction against the system catalog.
//
// Usage:  node scripts/db/generate-schema.mjs [env-file]
//   env-file defaults to .env.preview.local and must define DATABASE_URL,
//   POSTGRES_URL or WEALTH_DATABASE_URL. The URL is never printed.
import { neon } from '@neondatabase/serverless';
import { readFileSync, writeFileSync } from 'node:fs';

const envFile = process.argv[2] || '.env.preview.local';
const env = Object.fromEntries(readFileSync(envFile, 'utf8').split(/\r?\n/)
  .map(line => line.match(/^([A-Z0-9_]+)=(.*)$/)).filter(Boolean)
  .map(([, k, v]) => [k, v.replace(/^["']|["']$/g, '')]));
const url = env.WEALTH_DATABASE_URL || env.POSTGRES_URL || env.DATABASE_URL;
if (!url) throw new Error('No database URL in ' + envFile);
const sql = neon(url);
const ro = async q => (await sql.transaction([sql.query(q)], { readOnly: true }))[0];

const [extensions, sequences, tables, columns, constraints, indexes, server] = await Promise.all([
  ro(`select extname from pg_extension where extname<>'plpgsql' order by 1`),
  ro(`select sequencename name, data_type from pg_sequences where schemaname='public' order by 1`),
  ro(`select c.relname name from pg_class c join pg_namespace n on n.oid=c.relnamespace
      where n.nspname='public' and c.relkind='r' order by 1`),
  ro(`select c.relname tbl, a.attname col, format_type(a.atttypid,a.atttypmod) type, a.attnotnull as not_null,
        pg_get_expr(d.adbin,d.adrelid) def
      from pg_attribute a join pg_class c on c.oid=a.attrelid join pg_namespace n on n.oid=c.relnamespace
      left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
      where n.nspname='public' and c.relkind='r' and a.attnum>0 and not a.attisdropped
      order by c.relname,a.attnum`),
  ro(`select c.relname tbl, k.conname name, k.contype type, pg_get_constraintdef(k.oid) def
      from pg_constraint k join pg_class c on c.oid=k.conrelid join pg_namespace n on n.oid=c.relnamespace
      where n.nspname='public' and k.contype in ('p','u','c','f') order by c.relname,k.contype,k.conname`),
  ro(`select i.tablename tbl, i.indexname name, i.indexdef def from pg_indexes i
      where i.schemaname='public' and not exists (
        select 1 from pg_constraint k where k.conname=i.indexname and k.contype in ('p','u'))
      order by 1,2`),
  ro(`select current_setting('server_version') v`)
]);

const q = id => /^[a-z_][a-z0-9_]*$/.test(id) ? id : '"' + id.replace(/"/g, '""') + '"';
const out = [];
out.push(`-- Wealth Ledger database schema (structure only, no data).
-- Generated by scripts/db/generate-schema.mjs from the live database catalog
-- (PostgreSQL ${server[0].v}) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; regenerate instead.
--
-- Idempotent: safe to run on an empty database or re-run on an existing one.
-- Apply with psql or the Neon SQL editor (it contains DO blocks, so do NOT feed it
-- to scripts/migrate-db.mjs, which splits files on ';').
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f scripts/db/schema.sql
`);
out.push('BEGIN;\n');
for (const e of extensions) out.push(`CREATE EXTENSION IF NOT EXISTS ${q(e.extname)};`);
if (sequences.length) out.push('');
for (const s of sequences) out.push(`CREATE SEQUENCE IF NOT EXISTS ${q(s.name)} AS ${s.data_type};`);

// Tables with columns, primary keys, unique and check constraints. Foreign keys come later
// so that table order does not matter.
for (const { name } of tables) {
  const cols = columns.filter(c => c.tbl === name).map(c =>
    `  ${q(c.col)} ${c.type}${c.def != null ? ' DEFAULT ' + c.def : ''}${c.not_null ? ' NOT NULL' : ''}`);
  const cons = constraints.filter(k => k.tbl === name && k.type !== 'f')
    .map(k => `  CONSTRAINT ${q(k.name)} ${k.def}`);
  out.push(`\nCREATE TABLE IF NOT EXISTS ${q(name)} (\n${[...cols, ...cons].join(',\n')}\n);`);
}

// Sequences owned by serial columns.
const owned = columns.filter(c => /^nextval\('/.test(c.def || ''));
if (owned.length) out.push('');
for (const c of owned) {
  const seq = c.def.match(/nextval\('([^']+)'/)[1].replace(/::regclass$/, '');
  out.push(`ALTER SEQUENCE ${seq} OWNED BY ${q(c.tbl)}.${q(c.col)};`);
}

out.push('\n-- Foreign keys (added only if missing).');
for (const k of constraints.filter(k => k.type === 'f')) {
  out.push(`DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='${k.name}' AND conrelid='public.${k.tbl}'::regclass) THEN
    ALTER TABLE ${q(k.tbl)} ADD CONSTRAINT ${q(k.name)} ${k.def};
  END IF;
END $$;`);
}

out.push('\n-- Indexes not backing a primary key or unique constraint.');
for (const i of indexes) {
  out.push(i.def.replace(/^CREATE (UNIQUE )?INDEX /, (m, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `)
    .replace(/ ON public\./, ' ON ') + ';');
}
out.push('\nCOMMIT;\n');

const target = new URL('./schema.sql', import.meta.url);
writeFileSync(target, out.join('\n'));
console.log(`schema.sql written: ${tables.length} tables, ${constraints.length} constraints, ${indexes.length} extra indexes, ${sequences.length} sequences.`);
